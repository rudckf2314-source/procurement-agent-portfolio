def get_code_by_name(name_query: str) -> str:
    """
    업종명(부분 일치)으로 코드를 찾습니다.
    예: "정보통신" -> "0036"
    """
    q = name_query.strip().replace(" ", "")
    for code, name in INDUSTRY_MAP.items():
        if q in name.replace(" ", ""):
            return code
    return ""
